// Deterministic hashing + PRNG, ported verbatim from the design's data-pipeline.
// Used to synthesize the order book, resting-liquidity walls and other Level-2
// detail that Yahoo does not provide — seeding them per ticker+date+level keeps
// the book stable and reproducible through a session (predictable S/R).

export function hashStr(s) {
  let h = 1779033703 ^ s.length;
  for (let i = 0; i < s.length; i++) {
    h = Math.imul(h ^ s.charCodeAt(i), 3432918353);
    h = (h << 13) | (h >>> 19);
  }
  return h >>> 0;
}

export function mulberry32(a) {
  return function () {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
